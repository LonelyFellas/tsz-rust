use axum::{Router, extract::DefaultBodyLimit, routing::get};

use crate::{
    lexicon::{handler, validation::MAX_STEP_CONTENT_BODY_BYTES},
    state::AppState,
};

pub fn router() -> Router<AppState> {
    Router::new()
        .route(
            "/sentences",
            get(super::shared_sentences::list).post(super::shared_sentences::create),
        )
        .route(
            "/sentences/{id}",
            get(super::shared_sentences::get)
                .put(super::shared_sentences::update)
                .delete(super::shared_sentences::delete),
        )
        .route(
            "/sentences/{id}/trash",
            axum::routing::post(super::shared_sentences::trash::archive),
        )
        .route(
            "/sentences/{id}/untrash",
            axum::routing::post(super::shared_sentences::trash::restore),
        )
        .route("/sentences/targets", get(super::shared_sentences::targets))
        .route(
            "/sentences/{id}/publication-audio/check",
            axum::routing::post(handler::audio_publication::check_sentence),
        )
        .route(
            "/sentences/{id}/publication-audio/confirm",
            axum::routing::post(handler::audio_publication::confirm_sentence),
        )
        .route(
            "/sentences/{id}/publications",
            get(super::shared_sentences::reading::history)
                .post(super::shared_sentences::publication::publish),
        )
        .route(
            "/sentences/{id}/publications/{publication_id}",
            get(super::shared_sentences::reading::historical),
        )
        .route(
            "/sentences/{id}/publications/{publication_id}/rollback",
            axum::routing::post(super::shared_sentences::publication::rollback),
        )
        .route(
            "/sentences/{id}/withdrawal-impact",
            get(super::shared_sentences::publication::impact),
        )
        .route(
            "/sentences/{id}/withdraw",
            axum::routing::post(super::shared_sentences::publication::withdraw),
        )
        .route(
            "/sentences/{id}/restore",
            axum::routing::post(super::shared_sentences::publication::restore),
        )
        .route(
            "/entries/{entry_id}/sentences/{sentence_id}/visibility",
            axum::routing::put(super::shared_sentences::visibility::set_visibility),
        )
        .route("/assistant", axum::routing::post(super::assistant::ask))
        .route(
            "/assistant/form-candidates",
            axum::routing::post(super::assistant::candidates::generate),
        )
        .route(
            "/assistant/stream",
            axum::routing::post(super::assistant::ask_stream),
        )
        .route("/assistant/capability", get(super::assistant::capability))
        .route("/detections", axum::routing::post(handler::detect))
        .route(
            "/surface-match-snapshots/{snapshot_id}",
            get(handler::surface_match_snapshot_page),
        )
        .route(
            "/entries/{id}/annotation",
            axum::routing::patch(handler::commands::update_annotation),
        )
        .route("/entries", get(handler::list).post(handler::create))
        .route(
            "/entries/{id}/publication-audio/check",
            axum::routing::post(handler::audio_publication::check),
        )
        .route(
            "/entries/{id}/publication-audio/confirm",
            axum::routing::post(handler::audio_publication::confirm),
        )
        .route(
            "/entries/archive-impact",
            axum::routing::post(handler::lifecycle::archive_impact),
        )
        .route(
            "/entries/archive-batch",
            axum::routing::post(handler::archive_batch),
        )
        .route(
            "/entries/delete-batch",
            axum::routing::post(handler::delete_batch),
        )
        .route(
            "/entries/restore-batch",
            axum::routing::post(handler::restore_batch),
        )
        .route(
            "/entries/publications/batch",
            axum::routing::post(handler::commands::publish_batch),
        )
        .route("/entries/stats", get(handler::stats))
        .route("/entries/creators", get(handler::creators))
        .route("/entries/related-search", get(handler::related_search))
        .route(
            "/entries/related-suggestions",
            get(super::related_suggestions::suggest),
        )
        .route(
            "/entries/{id}/relation-senses",
            get(super::related_suggestions::senses),
        )
        .route(
            "/entries/{id}",
            get(handler::get).delete(handler::delete_draft),
        )
        .route(
            "/entries/{id}/inbound-references",
            get(handler::inbound_references),
        )
        .route(
            "/entries/{id}/archive",
            axum::routing::post(handler::archive),
        )
        .route(
            "/entries/{id}/restore",
            axum::routing::post(handler::restore),
        )
        .route(
            "/entries/{id}/publications",
            get(handler::list_publications).post(handler::publish),
        )
        .route(
            "/entries/{id}/publications/{publication_id}",
            get(handler::get_publication),
        )
        .route(
            "/entries/{id}/publications/{publication_id}/rollback",
            axum::routing::post(handler::rollback_publication),
        )
        .route(
            "/entries/{id}/publications/{publication_id}/restore-draft",
            axum::routing::post(handler::restore_draft_from_publication),
        )
        // 只有这三条路由承载整步草稿内容，需要高于 axum 默认 2 MiB 的请求体上限。
        // 其余接口的请求体都被自身契约框住（批量最多 100 条、其余是定长字段），
        // 继续吃默认值即可，不跟着放宽。
        .route(
            "/entries/{id}/steps/forms/impact",
            axum::routing::post(handler::preview_forms_impact)
                .layer(DefaultBodyLimit::max(MAX_STEP_CONTENT_BODY_BYTES)),
        )
        .route(
            "/entries/{id}/steps/forms",
            axum::routing::put(handler::save_forms)
                .layer(DefaultBodyLimit::max(MAX_STEP_CONTENT_BODY_BYTES)),
        )
        .route(
            "/entries/{id}/steps/meanings",
            axum::routing::put(handler::save_meanings)
                .layer(DefaultBodyLimit::max(MAX_STEP_CONTENT_BODY_BYTES)),
        )
        .route(
            "/entries/component-targets/search",
            axum::routing::post(handler::search_component_targets),
        )
        .route(
            "/entries/{id}/validate",
            axum::routing::post(handler::validate),
        )
        .route(
            "/audio-assets/upload-url",
            axum::routing::post(crate::lexicon::audio_assets::handler::create_audio_upload),
        )
        .route(
            "/audio-assets",
            axum::routing::post(crate::lexicon::audio_assets::handler::confirm_audio_asset),
        )
        .route(
            "/audio-assets/{id}/content",
            get(crate::lexicon::audio_assets::handler::audio_asset_content),
        )
        .route(
            "/audio-assets/{id}/url",
            get(crate::lexicon::audio_assets::handler::audio_asset_url),
        )
}
